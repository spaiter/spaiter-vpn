package deploy

import (
	"fmt"
	"path/filepath"
	"strings"
)

// LogrotateFileName is what the generator writes into the deployment
// directory.
const LogrotateFileName = "logrotate.conf"

// LogrotateMaxSize is the size at which a log is rotated regardless of the
// daily schedule. Chosen to match the hand-built deployment this was modelled
// on, where it has held a debug-level log to a workable size for months.
const LogrotateMaxSize = "50M"

// LogrotateKeep is how many rotations to retain.
const LogrotateKeep = 7

// Logrotate renders a logrotate stanza for the deployment's log.
//
// This exists because the core has no rotation of its own: log.output is a
// plain append-only file, and at debug level it grows without limit. The
// failure that follows is not a lost log — it is a full disk, and a full disk
// takes the server down.
//
// `copytruncate` is the load-bearing choice and not the obvious one. logrotate
// normally renames the file and expects the writer to reopen it; the core holds
// its log open and reopens only when it reloads its whole configuration. So
// without copytruncate the core would keep writing into the renamed inode and
// the fresh file would stay empty — the log would appear to stop. The
// alternative, a postrotate signal, means SIGHUP, and the core answers that by
// closing and recreating its instance, which drops every live session. Copying
// and truncating loses at most the lines written during the copy; the other
// options lose the log entirely or lose everyone's connection.
func (p Params) Logrotate() string {
	logPath := filepath.Join(p.ConfigDir, "sing-box.log")

	var b strings.Builder
	b.WriteString("# Generated by spaiter-vpn.\n")
	b.WriteString("#\n")
	b.WriteString("# Install with:\n")
	fmt.Fprintf(&b, "#   cp %s /etc/logrotate.d/spaiter-vpn\n", filepath.Join(p.ConfigDir, LogrotateFileName))
	b.WriteString("#   logrotate --debug /etc/logrotate.d/spaiter-vpn   # dry run first\n")
	b.WriteString("#\n")
	b.WriteString("# The core has no rotation of its own and its log is append-only, so at\n")
	b.WriteString("# debug level it grows until the disk is full — which takes the server\n")
	b.WriteString("# down, rather than merely losing logs.\n")
	b.WriteString("#\n")
	b.WriteString("# copytruncate is required, not stylistic. The core holds this file open\n")
	b.WriteString("# and reopens it only when it reloads its entire configuration, so a\n")
	b.WriteString("# plain rename would leave it writing to the old inode while the new file\n")
	b.WriteString("# stayed empty. The alternative — a postrotate signal — means SIGHUP,\n")
	b.WriteString("# which the core answers by recreating its instance and dropping every\n")
	b.WriteString("# live session.\n")
	fmt.Fprintf(&b, "%s {\n", logPath)
	b.WriteString("    daily\n")
	fmt.Fprintf(&b, "    maxsize %s\n", LogrotateMaxSize)
	fmt.Fprintf(&b, "    rotate %d\n", LogrotateKeep)
	b.WriteString("    compress\n")
	// delaycompress leaves the most recent rotation uncompressed, which is the
	// one anybody investigating an incident actually wants to read.
	b.WriteString("    delaycompress\n")
	b.WriteString("    copytruncate\n")
	b.WriteString("    missingok\n")
	b.WriteString("    notifempty\n")
	b.WriteString("}\n")
	return b.String()
}
