// Package deploy renders the files that run the generated configuration:
// a compose project and the environment it reads.
package deploy

import (
	"fmt"
	"sort"
	"strings"
)

// The compose service names. Exported constants rather than literals in the
// renderers, because the health wait has to know exactly which services must be
// running: a service renamed in one place and not the other would make the wait
// pass while the thing it was waiting for is absent.
const (
	CoreServiceName   = "sing-box"
	ReloadServiceName = "sing-box-reload"
	BotServiceName    = "vpn-bot"
)

// Params describes the host-side layout of a deployment.
type Params struct {
	// Image is the sing-box image to run.
	Image string
	// ConfigDir is the host directory mounted at /etc/sing-box. It holds
	// config.json, the log file and the per-user stats database.
	ConfigDir string
	// CacheDir is the host directory mounted at /var/lib/sing-box.
	CacheDir string
	// CertificateDir, when set, is mounted read-only at /etc/certs. Tier A
	// needs no certificates, so it is normally empty.
	CertificateDir string
	// XDPInterfaces is recorded in the environment file for reference; the
	// interface list itself lives in the generated config.
	XDPInterfaces []string
	// Reload configures the sidecar that replaces the host-side reload unit.
	Reload Reload
	// Bot configures the provisioning bot's service.
	Bot Bot
}

// Compose renders the compose project.
//
// Three things here are load-bearing rather than conventional:
//
//   - host networking, because the AmneziaWG endpoints bind real UDP ports and
//     the XDP blocker attaches to a host interface;
//   - NET_ADMIN, BPF and SYS_ADMIN, which are what XDP program loading needs;
//   - the whole directory is mounted, because sing-box rewrites the config
//     through config_output_path and keeps its stats database beside it;
//   - `-c config.json` rather than `-C <dir>`: the directory also holds the
//     bot's bot.json and bot-management.json, and `-C` merges every *.json it
//     finds, so the core would refuse to start whenever the bot is enabled.
func (p Params) Compose() string {
	var b strings.Builder
	b.WriteString("# Generated by spaiter-vpn. Edit the generator, not this file:\n")
	b.WriteString("# `spaiter-vpn init` overwrites it.\n")
	b.WriteString("services:\n")
	fmt.Fprintf(&b, "  %s:\n", CoreServiceName)
	fmt.Fprintf(&b, "    image: %s\n", p.Image)
	b.WriteString("    container_name: sing-box\n")
	b.WriteString("    restart: always\n")
	// Host networking: the endpoints bind real ports and the XDP program
	// attaches to a host interface. A bridge network would hide both.
	b.WriteString("    network_mode: host\n")
	b.WriteString("    cap_add:\n")
	b.WriteString("      - NET_ADMIN\n")
	b.WriteString("      - BPF\n")
	b.WriteString("      - SYS_ADMIN\n")
	b.WriteString("    volumes:\n")
	fmt.Fprintf(&b, "      - %s:/etc/sing-box\n", p.ConfigDir)
	fmt.Fprintf(&b, "      - %s:/var/lib/sing-box\n", p.CacheDir)
	if p.CertificateDir != "" {
		fmt.Fprintf(&b, "      - %s:/etc/certs:ro\n", p.CertificateDir)
	}
	b.WriteString("    command: -D /var/lib/sing-box -c /etc/sing-box/config.json run\n")
	if p.Reload.Enabled {
		b.WriteString("\n")
		b.WriteString(p.Reload.composeService(p))
	}
	if p.Bot.Enabled {
		b.WriteString("\n")
		b.WriteString(p.Bot.composeService(p))
	}
	return b.String()
}

// Services lists every service this deployment's compose project defines, in
// start order.
func (p Params) Services() []string {
	services := []string{CoreServiceName}
	if p.Reload.Enabled {
		services = append(services, ReloadServiceName)
	}
	if p.Bot.Enabled {
		services = append(services, BotServiceName)
	}
	return services
}

// ServicesInProject reports which of this package's services a generated
// compose file defines.
//
// Intersected with the names this package can emit rather than parsed as YAML,
// and that is the point: it cannot be made to report a service that is not
// ours, whatever else is in the file. It exists so a rollback can health-check
// the generation it just restored instead of the one that failed — those differ
// exactly when the convergence was turning the bot on or off.
func ServicesInProject(project []byte) []string {
	text := string(project)
	var found []string
	for _, name := range []string{CoreServiceName, ReloadServiceName, BotServiceName} {
		if strings.Contains(text, "\n  "+name+":\n") {
			found = append(found, name)
		}
	}
	return found
}

// Env renders the environment file. It deliberately contains no secrets: the
// keys live in config.json and secrets.json, both 0600, and a third copy in a
// file that tooling habitually prints would be a gift to anyone reading logs.
func (p Params) Env() string {
	values := map[string]string{
		"SPAITER_VPN_IMAGE":          p.Image,
		"SPAITER_VPN_CONFIG_DIR":     p.ConfigDir,
		"SPAITER_VPN_CACHE_DIR":      p.CacheDir,
		"SPAITER_VPN_XDP_INTERFACES": strings.Join(p.XDPInterfaces, ","),
	}
	if p.CertificateDir != "" {
		values["SPAITER_VPN_CERT_DIR"] = p.CertificateDir
	}

	keys := make([]string, 0, len(values))
	for k := range values {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Generated by spaiter-vpn. Contains no secrets by design.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s=%s\n", k, values[k])
	}
	return b.String()
}
