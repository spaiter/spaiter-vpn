package deploy

import (
	"fmt"
	"strings"
)

// ReloadAgentScriptName is the file the generator writes beside the config and
// mounts into the sidecar.
const ReloadAgentScriptName = "reload-agent.sh"

// Reload describes the reload sidecar.
//
// It replaces a host-side systemd path unit that ran `docker restart sing-box`
// when a provisioning bot touched a marker file. Moving that into the compose
// project is not only about self-containment — it is a strict improvement on
// both axes that matter:
//
// Privilege. Restarting a container needs the Docker API, and a container with
// the Docker socket is root on the host. Signalling a process needs only to be
// in its PID namespace, which compose grants with `pid: service:sing-box`. The
// sidecar therefore holds no Docker access, no capabilities and no network: the
// worst a compromised one can do is signal the process it was built to signal.
//
// Failure mode. `docker restart` tears the container down unconditionally, so a
// config sing-box refuses leaves the service down. SIGHUP is handled in
// cmd_run.go by re-running the config check FIRST and keeping the existing
// instance alive if it fails. The blunt instrument is the one that loses the
// service on a bad config.
//
// Both drop live sessions — SIGHUP closes and recreates the instance — so this
// is still the fallback path, not the normal one. Users and peers are applied
// in place through the clash API, which touches nothing else. SIGHUP is for
// what that API ignores, route rules above all.
type Reload struct {
	// Enabled generates the sidecar.
	Enabled bool
	// MarkerPath is the host path whose modification triggers a reload. A
	// provisioning bot writes it; the sidecar only reads it.
	MarkerPath string
	// PollSeconds is how often the marker's mtime is read. inotify would be
	// tidier but the core image has no inotify tool, and a two-second poll on
	// one stat() is not worth a second image.
	PollSeconds int
}

// DefaultPollSeconds is the marker poll interval.
const DefaultPollSeconds = 2

// Script renders the agent.
//
// Written as a file rather than an inline compose `command:` so that it can be
// read and reviewed on the host, and so quoting it is not a three-way fight
// between YAML, the shell and Go.
func (r Reload) Script() string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by spaiter-vpn. Edit the generator, not this file.\n")
	b.WriteString("#\n")
	b.WriteString("# Watches a marker file and sends SIGHUP to sing-box, which makes it\n")
	b.WriteString("# re-read its config. Runs in sing-box's PID namespace, so it needs no\n")
	b.WriteString("# Docker access: it can signal that one process and nothing else.\n")
	b.WriteString("set -eu\n\n")
	b.WriteString(": \"${MARKER:?MARKER is required}\"\n")
	b.WriteString(": \"${POLL_SECONDS:=2}\"\n\n")
	b.WriteString("log() { echo \"reload-agent: $*\"; }\n\n")
	b.WriteString("log \"watching $MARKER every ${POLL_SECONDS}s\"\n\n")
	// The first observation is recorded without acting on it. Otherwise every
	// restart of the sidecar would signal a reload for a marker that had not
	// changed since the last one — and a reload drops sessions.
	b.WriteString("seen=\"\"\n")
	b.WriteString("first=1\n")
	b.WriteString("while :; do\n")
	b.WriteString("\tif [ -e \"$MARKER\" ]; then\n")
	b.WriteString("\t\tstamp=$(stat -c %Y \"$MARKER\" 2>/dev/null || echo \"\")\n")
	b.WriteString("\t\tif [ -n \"$stamp\" ] && [ \"$stamp\" != \"$seen\" ]; then\n")
	b.WriteString("\t\t\tseen=\"$stamp\"\n")
	b.WriteString("\t\t\tif [ \"$first\" = \"1\" ]; then\n")
	b.WriteString("\t\t\t\tfirst=0\n")
	b.WriteString("\t\t\t\tlog \"marker already present; recorded without reloading\"\n")
	b.WriteString("\t\t\telse\n")
	// Resolve the pid rather than assuming 1. It IS 1 today — the core image's
	// entrypoint is sing-box itself — but an assumption that silently signals
	// the wrong process is a poor trade for one pidof call.
	b.WriteString("\t\t\t\tpid=$(pidof sing-box 2>/dev/null || echo \"\")\n")
	b.WriteString("\t\t\t\tif [ -z \"$pid\" ]; then\n")
	b.WriteString("\t\t\t\t\tlog \"ERROR: no sing-box process in this PID namespace; is pid:service: set?\"\n")
	b.WriteString("\t\t\t\telif kill -HUP $pid; then\n")
	b.WriteString("\t\t\t\t\tlog \"marker changed; sent SIGHUP to $pid\"\n")
	b.WriteString("\t\t\t\telse\n")
	b.WriteString("\t\t\t\t\tlog \"ERROR: could not signal $pid\"\n")
	b.WriteString("\t\t\t\tfi\n")
	b.WriteString("\t\t\tfi\n")
	b.WriteString("\t\tfi\n")
	b.WriteString("\tfi\n")
	b.WriteString("\tsleep \"$POLL_SECONDS\"\n")
	b.WriteString("done\n")
	return b.String()
}

// composeService renders the sidecar's compose entry.
func (r Reload) composeService(p Params) string {
	poll := r.PollSeconds
	if poll <= 0 {
		poll = DefaultPollSeconds
	}

	var b strings.Builder
	fmt.Fprintf(&b, "  %s:\n", ReloadServiceName)
	fmt.Fprintf(&b, "    image: %s\n", p.Image)
	b.WriteString("    container_name: sing-box-reload\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    depends_on:\n")
	b.WriteString("      - sing-box\n")
	// The whole design in one line: sharing the PID namespace is what lets a
	// signal replace a Docker API call. Do not "simplify" this by mounting
	// /var/run/docker.sock — that hands the host to the sidecar.
	b.WriteString("    pid: service:sing-box\n")
	// Nothing to reach, so nothing to reach it from.
	b.WriteString("    network_mode: none\n")
	b.WriteString("    cap_drop:\n")
	b.WriteString("      - ALL\n")
	b.WriteString("    read_only: true\n")
	b.WriteString("    environment:\n")
	b.WriteString("      - MARKER=/markers/marker\n")
	fmt.Fprintf(&b, "      - POLL_SECONDS=%d\n", poll)
	b.WriteString("    volumes:\n")
	fmt.Fprintf(&b, "      - %s/%s:/%s:ro\n", p.ConfigDir, ReloadAgentScriptName, ReloadAgentScriptName)
	// Read-only, and the marker itself rather than its directory: the sidecar
	// has no reason to see anything else the writer keeps there.
	fmt.Fprintf(&b, "      - %s:/markers/marker:ro\n", r.MarkerPath)
	fmt.Fprintf(&b, "    entrypoint: [\"/bin/sh\", \"/%s\"]\n", ReloadAgentScriptName)
	return b.String()
}
