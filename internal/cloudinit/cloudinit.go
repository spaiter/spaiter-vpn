// Package cloudinit renders the user-data that turns a fresh VPS into a
// deployment with no shell session: cloud-init installs a signed release of
// this binary and runs bootstrap.
//
// It is the provider one-click path of phase 10, and it keeps the property the
// project holds everywhere else: nothing downloaded is trusted before it is
// verified. The release key is embedded and pinned by fingerprint; the
// signature over SHA256SUMS must be made by exactly that key; the tarball must
// match its line in SHA256SUMS. Only then is the binary installed and run.
package cloudinit

import (
	"bytes"
	_ "embed"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"text/template"
)

// ReleaseKey is the public half of the key that signs releases, and
// ReleaseFingerprint pins it.
//
//go:embed release-signing.asc
var ReleaseKey []byte

const ReleaseFingerprint = "6D4841065CBDB46F500A4367C0718B337F6155B7"

// DefaultReleaseBase is where signed releases are published; a release's
// directory is DefaultReleaseBase + "/" + tag, holding SHA256SUMS,
// SHA256SUMS.asc and the tarball — the layout the first-boot script expects.
const DefaultReleaseBase = "https://github.com/spaiter/spaiter-vpn/releases/download"

// Options is everything the user-data carries.
type Options struct {
	// Desired is the canonical desired-state document.
	Desired []byte
	// ReleaseBase is the directory URL holding SHA256SUMS, SHA256SUMS.asc and
	// the tarball; Version names the tarball.
	ReleaseBase string
	Version     string
	// SigningKey and Fingerprint replace the embedded release key, for a
	// release signed by another key.
	SigningKey  []byte
	Fingerprint string
	// Credentials are the secret files the desired state names. They travel in
	// the user-data, which the provider can read; see the command's warning.
	Credentials map[string][]byte
	// ClaimBot prints a one-time bot claim code to the console when the bot
	// has no configured admin.
	ClaimBot bool
}

var (
	versionPattern     = regexp.MustCompile(`^v[0-9A-Za-z.+-]{1,64}$`)
	fingerprintPattern = regexp.MustCompile(`^[0-9A-F]{40}$`)
	credentialPattern  = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$`)
)

// Render returns the #cloud-config document.
func Render(o Options) ([]byte, error) {
	if o.SigningKey == nil {
		o.SigningKey, o.Fingerprint = ReleaseKey, ReleaseFingerprint
	}
	switch {
	case !versionPattern.MatchString(o.Version):
		return nil, fmt.Errorf("version %q is not a release tag like v0.1.0", o.Version)
	case !fingerprintPattern.MatchString(o.Fingerprint):
		return nil, fmt.Errorf("signing-key fingerprint %q is not 40 upper-case hex digits", o.Fingerprint)
	case !strings.HasPrefix(o.ReleaseBase, "https://") && !strings.HasPrefix(o.ReleaseBase, "http://"):
		return nil, fmt.Errorf("release base %q is not an http(s) URL", o.ReleaseBase)
	case strings.ContainsAny(o.ReleaseBase, "'\"\\ \n$`"):
		return nil, fmt.Errorf("release base %q contains characters a shell would interpret", o.ReleaseBase)
	}
	names := make([]string, 0, len(o.Credentials))
	for name := range o.Credentials {
		if !credentialPattern.MatchString(name) {
			return nil, fmt.Errorf("credential name %q is not a plain file name", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)
	files := []file{
		{Path: "/run/spaiter-vpn-firstboot/release-signing.asc", Mode: "0600", Content: string(o.SigningKey)},
		{Path: "/run/spaiter-vpn-firstboot/desired.json", Mode: "0600", Content: string(o.Desired)},
	}
	for _, name := range names {
		files = append(files, file{Path: "/run/spaiter-vpn-firstboot/credentials/" + name, Mode: "0600", Content: string(o.Credentials[name])})
	}
	var script bytes.Buffer
	if err := firstboot.Execute(&script, map[string]any{
		"Base": strings.TrimRight(o.ReleaseBase, "/"), "Version": o.Version, "Fingerprint": o.Fingerprint,
		"Credentials": names, "ClaimBot": o.ClaimBot,
	}); err != nil {
		return nil, err
	}
	files = append(files, file{Path: "/run/spaiter-vpn-firstboot/firstboot.sh", Mode: "0700", Content: script.String()})

	var out bytes.Buffer
	out.WriteString("#cloud-config\n# Generated by `spaiter-vpn bootstrap cloud-init`. Holds credentials: treat it as a secret.\n")
	out.WriteString("package_update: true\npackages: [gnupg, curl, ca-certificates]\nwrite_files:\n")
	for _, f := range files {
		fmt.Fprintf(&out, "  - path: %s\n    permissions: '%s'\n    owner: root:root\n    content: |\n", f.Path, f.Mode)
		for _, line := range strings.Split(strings.TrimRight(f.Content, "\n"), "\n") {
			fmt.Fprintf(&out, "      %s\n", line)
		}
	}
	out.WriteString("runcmd:\n  - [/bin/sh, /run/spaiter-vpn-firstboot/firstboot.sh]\n")
	return out.Bytes(), nil
}

type file struct{ Path, Mode, Content string }

// firstboot verifies, installs and applies. Every step fails closed: set -e,
// and an unverified binary is never moved into place.
var firstboot = template.Must(template.New("firstboot").Parse(`#!/bin/sh
# spaiter-vpn first boot: verify a signed release, install it, apply.
set -eu
exec >>/var/log/spaiter-vpn-firstboot.log 2>&1
STAGE=/run/spaiter-vpn-firstboot
NAME=spaiter-vpn-{{.Version}}-linux-amd64
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
export GNUPGHOME="$WORK/gnupg"
mkdir -m 0700 "$GNUPGHOME"
gpg --batch --quiet --import "$STAGE/release-signing.asc"
cd "$WORK"
curl -fsSL --retry 5 -o SHA256SUMS '{{.Base}}/SHA256SUMS'
curl -fsSL --retry 5 -o SHA256SUMS.asc '{{.Base}}/SHA256SUMS.asc'
curl -fsSL --retry 5 -o "$NAME.tar.gz" '{{.Base}}/'"$NAME.tar.gz"
# The signature must be valid and made by the pinned key, not merely by some
# key that happens to be in this throwaway keyring.
gpg --batch --status-fd 1 --verify SHA256SUMS.asc SHA256SUMS | grep -q '^\[GNUPG:\] VALIDSIG {{.Fingerprint}} '
grep " $NAME.tar.gz\$" SHA256SUMS | sha256sum --check --strict -
tar -xzf "$NAME.tar.gz"
install -m 0755 "$NAME/spaiter-vpn" /usr/local/bin/spaiter-vpn
echo "spaiter-vpn {{.Version}} verified and installed"
{{range .Credentials}}/usr/local/bin/spaiter-vpn bootstrap credential {{.}} <"$STAGE/credentials/{{.}}"
{{end}}/usr/local/bin/spaiter-vpn bootstrap apply -yes -f "$STAGE/desired.json"
{{if .ClaimBot}}CODE=$(/usr/local/bin/spaiter-vpn bot claim-code | sed -n 's/^claim code: //p')
echo "spaiter-vpn: send '/claim $CODE' to your bot within 15 minutes" | tee /dev/console
{{end}}rm -rf "$STAGE"
echo "spaiter-vpn: deployment applied"
`))
